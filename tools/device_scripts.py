"""Device-side Bash payloads, rendered and transported by frame.py.

These are not host shell tools. The runtime and app journal formats remain
compatible with the verified Frame Pro deployment and its rollback records.
"""

RUNTIME = r"""# Generated by frame.py; run by Bash through Samsung's signed interpreter.
set -euo pipefail
export PATH=/usr/sbin:/usr/bin:/sbin:/bin
ACTION='@@ACTION@@'
SCOPE='@@SCOPE@@'
BUILD='@@BUILD@@'
STATE=/run/frame-runtime-v1
LOCK=/run/frame-runtime-v1.lock
fail() { printf 'ERROR: %s\n' "$*" >&2; exit 1; }
hash() { sha256sum -- "$1" | cut -d ' ' -f 1; }
inode() { stat -Lc '%d:%i' -- "$1"; }
phase() {
    local uptime idle
    read -r uptime idle < /proc/uptime
    printf 'TIMING scope=%s phase=%s monotonic_s=%s\n' "$SCOPE" "$1" "$uptime"
}
# Query once and validate every requested record before trusting any state.
# Paths/busnames have no MainPID property; services must supply a numeric one.
snapshot() {
    local output
    output=$(systemctl show "${selected[@]}" -p Id -p LoadState -p ActiveState -p MainPID -p UnitFileState) || return 1
    printf '%s\n\n' "$output" | awk -v names="${selected[*]}" '
        BEGIN { count=split(names, order, " "); for(i=1;i<=count;i++) if(wanted[order[i]]++) bad=1 }
        function field(key) { return value[key]=="" ? "-" : value[key] }
        function record( id,k) {
            if (!fields) return
            id=value["Id"]
            if (!(id in wanted) || seen[id]++ || !("LoadState" in value) ||
                !("ActiveState" in value) || !("UnitFileState" in value) ||
                value["LoadState"]=="" || value["ActiveState"]=="" ||
                (id ~ /[.]service$/ && value["MainPID"] !~ /^[0-9]+$/)) bad=1
            rows[id]=id "\t" value["LoadState"] "\t" value["ActiveState"] "\t" field("MainPID") "\t" field("UnitFileState")
            for(k in value) delete value[k]
            fields=0
        }
        /^$/ { record(); next }
        {
            pos=index($0,"=")
            key=substr($0,1,pos-1)
            if (!pos || key !~ /^(Id|LoadState|ActiveState|MainPID|UnitFileState)$/ || key in value) bad=1
            value[key]=substr($0,pos+1); fields++
        }
        END {
            record()
            for(i=1;i<=count;i++) if(seen[order[i]]!=1) bad=1
            if(bad) exit 1
            for(i=1;i<=count;i++) print rows[order[i]]
        }'
}
check_masks() {
    local records unit load active pid masked bad=0
    records=$(snapshot) || fail 'Invalid or incomplete unit status'
    while IFS=$'\t' read -r unit load active pid masked; do
        if [[ $load == masked && $masked == masked* &&
              -L /run/systemd/system/$unit && $(readlink /run/systemd/system/$unit) == /dev/null ]] &&
           { [[ $active == inactive ]] || [[ $unit == *.service && $active == failed ]]; } &&
           { [[ $unit != *.service ]] || [[ $pid == 0 ]]; }; then
            echo "MASK OK $unit"
        else
            echo "MASK DRIFT $unit load=$load masked=$masked active=$active pid=$pid"; bad=1
        fi
    done <<< "$records"
    return "$bad"
}
processes() { cat <<'PROCESSES'
@@PROCESSES@@
PROCESSES
}
check_processes() {
    local expected canonical proc actual found=0
    local -a targets=()
    while IFS= read -r expected; do
        [[ -n $expected ]] || continue
        [[ $expected == /* && -f $expected ]] || { echo "PROCESS PATH UNAVAILABLE $expected" >&2; return 1; }
        canonical=$(readlink -f "$expected") || return 1
        targets+=("$canonical")
    done < <(processes)
    (( ${#targets[@]} > 0 )) || return 0
    [[ ${1-} != paths-only ]] || return 0
    for proc in /proc/[0-9]*; do
        if ! actual=$(readlink "$proc/exe" 2>/dev/null); then
            if [[ -L $proc/exe ]]; then
                echo "PROCESS IDENTITY UNAVAILABLE ${proc##*/}" >&2; found=1
            fi
            continue
        fi
        for expected in "${targets[@]}"; do
            if [[ $actual == "$expected" || $actual == "$expected (deleted)" ]]; then
                echo "SURVIVING SERVICE PROCESS ${proc##*/} $actual"; found=1
            fi
        done
    done
    [[ $found == 0 ]] || return 1
    echo 'SELECTED SERVICE PROCESSES ABSENT'
}
certs() { cat <<'CERTS'
@@CERTS@@
CERTS
}
units() { cat <<'UNITS'
@@UNITS@@
UNITS
}
[[ $(id -u) == 0 ]] || fail 'UID 0 required'

if [[ $ACTION == inspect ]]; then
    id
    cat /etc/os-release
    printf 'Architecture: '; uname -m
    printf 'SMACK: '; cat /proc/self/attr/current
    printf '\nRoot-agent namespace: '; readlink /proc/self/ns/mnt
    printf 'PID 1 namespace: '; readlink /proc/1/ns/mnt
    if nsenter --mount=/proc/1/ns/mnt /bin/true; then
        echo 'PID 1 mount namespace entry: PASS'
    else
        echo 'PID 1 mount namespace entry: DENIED (global overlays unavailable)'
    fi
    while IFS=$'\t' read -r path before after file; do
        if [[ -f $path ]]; then
            actual=$(hash "$path")
            printf 'CERT %s expected=%s actual=%s\n' "$path" "$before" "$actual"
        else
            printf 'CERT %s MISSING\n' "$path"
        fi
    done < <(certs)
    while read -r unit; do
        systemctl show "$unit" -p Id -p LoadState -p ActiveState -p UnitFileState
    done < <(units)
    echo 'Inspection only. No certificate overlays, masks, or app-state changes applied.'
    exit 0
fi

[[ $(readlink /proc/self/ns/mnt) == "$(readlink /proc/1/ns/mnt)" ]] || fail 'Not in PID 1 mount namespace'
[[ ! -L $STATE && ! -L $LOCK ]] || fail 'Unexpected state/lock symlink'
[[ ! -e $STATE || $(stat -c '%u:%a' "$STATE") == 0:700 ]] || fail 'Unexpected state ownership/mode'

restore() {
    [[ -d $STATE ]] || { echo 'No runtime changes recorded.'; return 0; }
    local errors=0 path before after file unit was_active target
    # Journals are written before each mutation, including a possibly failed one.
    if [[ -f $STATE/certs.tsv ]]; then
        while IFS=$'\t' read -r path before after file; do
            if [[ -f $STATE/$file && $(inode "$path") == "$(inode "$STATE/$file")" ]]; then
                if umount -- "$path" && [[ $(hash "$path") == "$before" ]]; then
                    echo "RESTORED $path"
                else
                    echo "RESTORE FAILED $path" >&2; errors=1
                fi
            elif [[ -f $path && $(hash "$path") == "$before" ]]; then
                echo "ALREADY ORIGINAL $path"
            else
                echo "REFUSING changed or replaced mount: $path" >&2; errors=1
            fi
        done < "$STATE/certs.tsv"
    fi
    if [[ -f $STATE/units.tsv ]]; then
        while IFS=$'\t' read -r unit was_active; do
            target=/run/systemd/system/$unit
            if [[ -L $target && $(readlink "$target") == /dev/null ]]; then
                if ! systemctl unmask --runtime --no-reload "$unit"; then errors=1; fi
            elif [[ -e $target || -L $target ]]; then
                echo "REFUSING changed runtime unit: $unit" >&2; errors=1
            fi
        done < "$STATE/units.tsv"
        if ! systemctl daemon-reload; then errors=1; fi
        while IFS=$'\t' read -r unit was_active; do
            if [[ $was_active == active || $was_active == activating ]]; then
                if ! systemctl start "$unit" || ! systemctl is-active --quiet "$unit"; then
                    echo "RESTART FAILED $unit" >&2; errors=1
                fi
            fi
        done < "$STATE/units.tsv"
    fi
    if [[ $errors != 0 ]]; then
        echo "Restore incomplete. Journal retained at $STATE; a cold boot clears runtime mounts/masks." >&2
        return 1
    fi
    rm -rf -- "$STATE" || return 1
    echo 'RESTORED. Existing application TLS caches may still need an app restart.'
}

if [[ $ACTION == status ]]; then
    [[ -d $STATE ]] || { echo 'No runtime changes recorded for this boot.'; exit 0; }
    [[ -f $STATE/complete ]] || fail 'Previous apply incomplete; run restore'
    bad=0
    if [[ -f $STATE/certs.tsv ]]; then
        while IFS=$'\t' read -r path before after file; do
            if [[ -f $path && $(inode "$path") == "$(inode "$STATE/$file")" && $(hash "$path") == "$after" ]]; then
                echo "OVERLAY OK $path"
            else
                echo "OVERLAY DRIFT $path"; bad=1
            fi
        done < "$STATE/certs.tsv"
    fi
    if [[ -f $STATE/units.tsv ]]; then
        selected=()
        while IFS=$'\t' read -r unit was_active; do selected+=("$unit"); done < "$STATE/units.tsv"
        (( ${#selected[@]} > 0 )) || fail 'Empty unit journal'
        if ! check_masks; then bad=1; fi
        if ! check_processes; then bad=1; fi
    fi
    exit "$bad"
fi

# Serialize mutations. A stale lock after a killed process requires inspection;
# do not guess that another apply has finished.
mkdir -m 700 -- "$LOCK" || fail "Another operation or stale lock exists: $LOCK"
rollback_needed=0
finish() {
    rc=$?
    trap - EXIT
    if [[ $rc != 0 && $rollback_needed == 1 ]]; then
        echo 'Apply failed; attempting journaled restore.' >&2
        if ! restore; then echo 'Automatic restore incomplete; see retained journal.' >&2; fi
    fi
    rmdir -- "$LOCK" || rc=1
    exit "$rc"
}
trap finish EXIT
trap 'exit 130' INT
trap 'exit 143' TERM
if [[ $ACTION == restore ]]; then
    [[ ! -e /opt/usr/share/samshush-boot-v1 ]] || fail 'Remove automatic reapplication with startup remove before restoring runtime controls'
    restore; exit 0
fi
[[ $ACTION == apply ]] || fail 'Unknown action'
[[ ! -e $STATE ]] || fail 'Changes already recorded; run status or restore before applying again'
[[ $(uname -m) == aarch64 ]] || fail 'Expected AArch64 Frame Pro'
[[ $(stat -f -c %T /run) == tmpfs ]] || fail '/run is not tmpfs; per-boot restoration assumptions do not hold'
grep -Fxq "BUILD_ID=$BUILD" /etc/os-release || fail 'Different firmware build; inspect and prepare matching policy'

# Validate the complete requested scope before changing any target.
if [[ $SCOPE == certificates || $SCOPE == both ]]; then
    for tool in mount umount cp sha256sum stat chsmack; do command -v "$tool" >/dev/null || fail "Missing $tool"; done
    while IFS=$'\t' read -r path before after file; do
        [[ -f $path && ! -L $path ]] || fail "Expected regular certificate file: $path"
        [[ $(hash "$path") == "$before" ]] || fail "Certificate preimage changed: $path"
        [[ $(hash "$FRAME_STAGE/$file") == "$after" ]] || fail "Staged certificate mismatch: $file"
    done < <(certs)
fi
if [[ $SCOPE == services || $SCOPE == both || $SCOPE == voice ]]; then
    phase preflight_begin
    selected=()
    while read -r unit; do [[ -n $unit ]] && selected+=("$unit"); done < <(units)
    (( ${#selected[@]} > 0 )) || fail 'No units selected'
    records=$(snapshot) || fail 'Invalid or incomplete unit preflight'
    while IFS=$'\t' read -r unit load active pid masked; do
        [[ $load == loaded ]] || fail "Unit absent or already masked: $unit"
        [[ $active == active || $active == activating || $active == inactive || $active == failed ]] || fail "Unsupported unit state: $unit=$active"
        [[ ! -e /run/systemd/system/$unit && ! -L /run/systemd/system/$unit ]] || fail "Existing runtime override: $unit"
    done <<< "$records"
    check_processes paths-only || fail 'Selected service process path unavailable'
    phase preflight_end
fi
mkdir -m 700 -- "$STATE"
rollback_needed=1
printf '%s\n' "$SCOPE" > "$STATE/scope"
if [[ $SCOPE == certificates || $SCOPE == both ]]; then
    while IFS=$'\t' read -r path before after file; do
        [[ $(hash "$path") == "$before" ]] || fail "Certificate changed since preflight: $path"
        # Preserve mode, ownership and SMACK/xattrs before changing file content.
        cp --preserve=all -- "$path" "$STATE/$file"
        source_labels=$(chsmack "$path" | cut -d ' ' -f 2-)
        overlay_labels=$(chsmack "$STATE/$file" | cut -d ' ' -f 2-)
        [[ $source_labels == "$overlay_labels" ]] || fail "SMACK labels were not preserved: $path"
        cat "$FRAME_STAGE/$file" > "$STATE/$file"
        [[ $(hash "$STATE/$file") == "$after" ]] || fail "Overlay copy mismatch: $path"
        printf '%s\t%s\t%s\t%s\n' "$path" "$before" "$after" "$file" >> "$STATE/certs.tsv"
        [[ $(hash "$path") == "$before" ]] || fail "Certificate changed before mount: $path"
        mount --bind "$STATE/$file" "$path"
        mount -o remount,bind,ro "$path"
        [[ $(inode "$path") == "$(inode "$STATE/$file")" && $(hash "$path") == "$after" ]] || fail "Overlay readback failed: $path"
        echo "OVERLAID $path"
    done < <(certs)
fi
if [[ $SCOPE == services || $SCOPE == both || $SCOPE == voice ]]; then
    phase journal_begin
    records=$(snapshot) || fail 'Invalid or incomplete unit state before masking'
    # Validate the whole batch again before recording or mutating any unit.
    while IFS=$'\t' read -r unit load active pid masked; do
        [[ $load == loaded ]] || fail "Unit changed since preflight: $unit"
        [[ $active == active || $active == activating || $active == inactive || $active == failed ]] || fail "Unit changed since preflight: $unit"
        [[ ! -e /run/systemd/system/$unit && ! -L /run/systemd/system/$unit ]] || fail "Runtime override appeared: $unit"
    done <<< "$records"
    while IFS=$'\t' read -r unit load active pid masked; do
        printf '%s\t%s\n' "$unit" "$active" >> "$STATE/units.tsv"
    done <<< "$records"
    phase mask_begin
    systemctl mask --runtime --no-reload "${selected[@]}"
    phase reload_begin
    systemctl daemon-reload
    phase stop_begin
    systemctl stop "${selected[@]}"
    phase readback_begin
    check_masks || fail 'Unit batch readback failed'
    check_processes || fail 'Selected service process remains or cannot be checked'
    phase readback_end
fi
touch "$STATE/complete"
rollback_needed=0
echo 'APPLIED for this boot. This does not establish app-wide CA distrust, app-manager launch blocking, or microphone shutdown.'
if [[ $SCOPE == voice ]]; then
    echo 'Voice apps can outlive their launcher units or auto-restart. Run voice-audit; verify physical microphone controls separately.'
fi
"""

